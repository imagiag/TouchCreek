// Generates daisy/creek/config.h from web/engine/creek-config.js, so the JS and
// C++ engines share one set of constants.   node tools/gen-config.js
const fs = require('fs'), path = require('path');
const { CK, CK_ZONES, CK_LAYERS } = require('../web/engine/creek-config.js');
const num = (v) => {
  if (Number.isInteger(v)) return String(v);
  let s = String(v); if (!/[.e]/.test(s)) s += '.0'; return s + 'f';
};
let out = `// GENERATED by tools/gen-config.js from web/engine/creek-config.js — do not edit.
#pragma once
#include <stdint.h>

namespace creek {
namespace ck {

constexpr int ZONES = ${CK_ZONES};
constexpr int LAYERS = ${CK_LAYERS};
`;
// counts and sizes are ints; everything else is float (no accidental integer maths)
const INTS = new Set(['CONTROL_HZ', 'MICRO', 'VOICES', 'VOICE_SLOTS', 'MAX_BIRTHS_PER_MICRO', 'QUEUE_SIZE', 'EDDY_SLOTS', 'FALLS_VOICES', 'SURF_VOICES']);
const flt = (x) => (Number.isInteger(x) ? x + '.0f' : num(x));
for (const [k, v] of Object.entries(CK)) {
  if (Array.isArray(v)) out += `constexpr float ${k}[${v.length}] = {${v.map(flt).join(', ')}};\n`;
  else if (INTS.has(k)) out += `constexpr int ${k} = ${v};\n`;
  else out += `constexpr float ${k} = ${flt(v)};\n`;
}
out += `
} // namespace ck
} // namespace creek
`;
const dst = path.join(__dirname, '../daisy/creek/config.h');
fs.mkdirSync(path.dirname(dst), { recursive: true });
fs.writeFileSync(dst, out);
console.log('wrote', path.relative(process.cwd(), dst));
